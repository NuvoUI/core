// Generates src/styles/functions/_default-scales.scss: the shade scales of the default role and palette colors.
//
// Usage: node scripts/generate-scales.mjs           (or: npm run scales) writes the file
//        node scripts/generate-scales.mjs --check   exits with code 1 when the file differs from the generator
//
// Runs the real generator (generate-color-scale() in functions/_color-scale.scss) on every value of the default
// $semantic-colors and $color-primitives. create-color-scale() returns these maps for a color whose inspected
// value matches a key, so the defaults are not generated on every compile; any other color still runs the
// generator. Re-run after a change to the generator or to a default color.
import fs from 'node:fs';
import path from 'node:path';
import * as sass from 'sass';
import { CORE_DIR, STYLES_DIR } from '../test/helpers.mjs';

const OUT_FILE = path.join(STYLES_DIR, 'functions', '_default-scales.scss');

// Debug lines are tab separated: inspected color, then stop and shade pairs
const SOURCE = `
@use "sass:map";
@use "sass:meta";
@use "config/colors" as config-color;
@use "functions/color-scale" as fn-scale;
@each $name, $value in map.merge(config-color.$semantic-colors, config-color.$color-primitives) {
    $scale: fn-scale.generate-color-scale($value);
    $line: meta.inspect($value);
    @each $stop, $shade in $scale {
        $line: $line + "\\9 #{$stop}\\9 #{meta.inspect($shade)}";
    }
    @debug $line;
}
`;

function generate() {
    const lines = [];
    sass.compileString(SOURCE, {
        loadPaths: [STYLES_DIR],
        logger: {
            debug(message) {
                lines.push(message);
            },
            warn(message) {
                throw new Error(
                    `generate-scales: unexpected warning: ${message}`
                );
            },
        },
    });
    const seen = new Set();
    const entries = [];
    for (const line of lines) {
        const [key, ...stops] = line.split('\t');
        if (seen.has(key)) {
            continue;
        }
        seen.add(key);
        const body = [];
        for (let i = 0; i < stops.length; i += 2) {
            body.push(`        ${stops[i]}: ${stops[i + 1]},`);
        }
        entries.push(`    "${key}": (\n${body.join('\n')}\n    ),`);
    }
    return [
        '// Generated by scripts/generate-scales.mjs. Do not edit: run `npm run scales` after changing the generator',
        '// or a default color. create-color-scale() returns these scales for colors whose inspected value matches a',
        '// key, so the default role and palette colors are not shaded on every compile; npm test fails when stale.',
        '$default-color-scales: (',
        ...entries,
        ');',
        '',
    ].join('\n');
}

function run() {
    const content = generate();
    const relative = path.relative(CORE_DIR, OUT_FILE);
    if (process.argv.includes('--check')) {
        const current = fs.existsSync(OUT_FILE)
            ? fs.readFileSync(OUT_FILE, 'utf8')
            : '';
        if (current !== content) {
            console.log(`scales: ${relative} is stale. Run npm run scales.`);
            process.exit(1);
        }
        console.log(`scales: ${relative} matches the generator`);
        return;
    }
    fs.writeFileSync(OUT_FILE, content);
    console.log(`scales: wrote ${relative}`);
}

run();
